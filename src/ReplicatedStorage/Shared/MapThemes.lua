--!strict
-- How each biome looks and feels: a valley walled in by cliffs, Slime RNG
-- style. Read by the server's MapBuilder (ground, cliffs, keys, props) and
-- the client's ZoneAmbience (lighting, title card, gravity). Keyed by
-- Shared/Zones ids (which predate the biome names, see Shared/Zones).

export type Theme = {
	Subtitle: string,
	-- Ground
	Floor: Color3,
	FloorMaterial: Enum.Material,
	Patches: { Color3 }, -- low-poly ground patches scattered over the floor
	Path: Color3, -- the trail from the entrance, past the keyboard, to the exit
	PathMaterial: Enum.Material,
	-- Cliffs walling the valley in
	Rock: { Color3 }, -- per-chunk colours
	RockMaterial: Enum.Material,
	Cap: Color3?, -- grass / snow on the cliff tops
	CapMaterial: Enum.Material?,
	CliffHeight: number,
	CliffStyle: string, -- "Rock" | "Cloud"
	Water: Color3?, -- sea along the +X side instead of cliffs
	Roof: boolean, -- cave ceiling
	-- Keyboard
	Plate: Color3,
	Trim: Color3,
	Keys: { Color3 }, -- keycap colours, cycled per row
	KeyMaterial: Enum.Material,
	Props: { [string]: number }, -- MapBuilder prop name → weight
	PropCount: number,
	Weather: string?, -- "Snow" | "Embers" | "Sparkle" | "Fireflies"
	-- Lighting while the local player is in the zone
	ClockTime: number,
	Ambient: Color3,
	OutdoorAmbient: Color3,
	FogColor: Color3,
	FogEnd: number,
	AtmosphereColor: Color3,
	AtmosphereDensity: number,
	Gravity: number,
}

local function rgb(r: number, g: number, b: number): Color3
	return Color3.fromRGB(r, g, b)
end

