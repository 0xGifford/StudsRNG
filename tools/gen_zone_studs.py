#!/usr/bin/env python3
"""Writes the zone 8-34 studs into src/ReplicatedStorage/Shared/Studs.lua
(between the "-- Zones 8-34" marker and the boss drops), from the names and
the curve below:  python3 tools/gen_zone_studs.py

Ids are saved in player data: once the game is live, don't rename a stud;
only add zones / studs and re-run. Balance with tools/simulate.py.
"""
import math, colorsys, re
from pathlib import Path

EPIC_START = 20_000   # zone 8's Epic is 1 in this
GROWTH = 1.24         # each zone's studs are this much rarer than the last
TIERS = [("Epic", 1), ("Legendary", 7), ("Mythic", 45)]
SECRET = 600          # x the zone's Epic, every SECRET_EVERY zones
def multiplier(one_in): return round(0.75 * one_in ** 0.3, 1 if one_in < 1e5 else 0)

NAMES = {
 8:("Lantern","Beacon","Lighthouse"), 9:("Ripple","Undertow","Maelstrom"), 10:("Cinder","Magma","Inferno"),
 11:("Frost","Glacier","Avalanche"), 12:("Thistle","Briar","Thornwood"), 13:("Gear","Clockwork","Automaton"),
 14:("Petal","Bloom","Everbloom"), 15:("Spark","Volt","Tempest"), 16:("Quartz","Obsidian","Monolith"),
 17:("Dune","Mirage","Sandstorm"), 18:("Fern","Canopy","Worldtree"), 19:("Ink","Shadow","Eclipse"),
 20:("Copper","Bronze","Colossus"), 21:("Cloud","Zephyr","Skyward"), 22:("Shell","Pearl","Leviathan"),
 23:("Rune","Sigil","Arcana"), 24:("Ember Fox","Phoenix","Firebird"), 25:("Orbit","Pulsar","Galaxy"),
 26:("Candy","Sugarstorm","Gumdrop King"), 27:("Echo","Resonance","Harmony"), 28:("Neon","Hologram","Mainframe"),
 29:("Moonlit","Lunar","Nightfall"), 30:("Crystal","Prismatic","Kaleidoscope"), 31:("Storm","Thunderhead","Cyclone"),
 32:("Aurora","Borealis","Celestial"), 33:("Omen","Fate","Destiny"), 34:("Crown","Sovereign","Eternity"),
}
SECRETS = {10:"Dragonheart", 14:"Gaia", 18:"Yggdrasil", 22:"Abyssal King", 26:"Wonderland", 30:"Infinity", 34:"Genesis"}
MATERIAL = {"Epic":("Glass","Neon"),"Legendary":("Foil","Neon"),"Mythic":("Neon","ForceField"),"Secret":("ForceField","ForceField")}
PARTICLE = {"Epic":("Sparkle","Shine"),"Legendary":("Stars","Flare"),"Mythic":("Flare","Glitch"),"Secret":("Void","Glitch")}

def round2(v):
    s = 10 ** max(0, math.floor(math.log10(v)) - 1)
    return int(math.floor(v / s + 0.5) * s)

def color(n, k):
    r, g, b = colorsys.hsv_to_rgb(((n * 0.137) + k * 0.06) % 1, 0.55 + 0.1 * k, 1.0)
    return int(r * 255), int(g * 255), int(b * 255)

def block():
    lines = ["\t-- Zones 8-34 (zone exclusive): three a zone, a Secret every fourth.",
             "\t-- Generated by tools/gen_zone_studs.py (balance: tools/simulate.py)."]
    for n in range(8, 35):
        epic = EPIC_START * GROWTH ** (n - 8)
        tiers = [(r, epic * f) for r, f in TIERS]
        if n in SECRETS:
            tiers.append(("Secret", epic * SECRET))
        lines.append(f"\t-- Zone {n}")
        for k, (rarity, base) in enumerate(tiers):
            name = NAMES[n][k] if k < 3 else SECRETS[n]
            sid = "Z%02d%s" % (n, name.replace(" ", ""))
            one = round2(base)
            r, g, b = color(n, k)
            light = "" if rarity == "Epic" else ", Light = true"
            lines.append(f'\t{{ Id = "{sid}", Name = "{name}", Rarity = "{rarity}", OneIn = {one:_}, Multiplier = {multiplier(one):g}, World = "{n:03d}",')
            lines.append(f'\t\tColor = Color3.fromRGB({r}, {g}, {b}), Material = Enum.Material.{MATERIAL[rarity][n % 2]}, Particle = "{PARTICLE[rarity][n % 2]}"{light} }},')
    return "\n".join(lines) + "\n\n"

path = Path(__file__).resolve().parent.parent / "src" / "ReplicatedStorage" / "Shared" / "Studs.lua"
text = path.read_text()
start = text.index("\t-- Zones 8-34 (zone exclusive)")
end = text.index("\t-- Boss drops (never rolled: Systems/Drops)")
path.write_text(text[:start] + block() + text[end:])
print("wrote zone studs into", path.name)
